package models;

/**
 *
 * @author admin
 */
public class Tutor_profiles {
    private int id;
    private int userId;
    private String bio;
    private String experience;
    private double price;
    private String area;
    private String status;

    public Tutor_profiles(int id, int userId, String bio, String experience, double price, String area, String status) {
        this.id = id;
        this.userId = userId;
        this.bio = bio;
        this.experience = experience;
        this.price = price;
        this.area = area;
        this.status = status;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public int getUserId() {
        return userId;
    }

    public void setUserId(int userId) {
        this.userId = userId;
    }

    public String getBio() {
        return bio;
    }

    public void setBio(String bio) {
        this.bio = bio;
    }

    public String getExperience() {
        return experience;
    }

    public void setExperience(String experience) {
        this.experience = experience;
    }

    public double getPrice() {
        return price;
    }

    public void setPrice(double price) {
        this.price = price;
    }

    public String getArea() {
        return area;
    }

    public void setArea(String area) {
        this.area = area;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }
    
    
}
